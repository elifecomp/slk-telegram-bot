def get_operator(phone):
    """Определяет оператора по номеру телефона"""
    if not phone:
        return ""
    clean = ''.join(c for c in phone if c.isdigit())
    if len(clean) < 11:
        return ""
    code = clean[-10:-7]
    op = OPERATORS.get(code, '')
    return f" | 📶 {op}" if op else ""
